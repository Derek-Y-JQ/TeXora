'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vm = require('node:vm');
const {searchProject, replaceProject} = require('../electron/lib/search');
const {ProjectService} = require('../electron/lib/fsops');
(async () => {
  const dir = await fs.mkdtemp(path.resolve('.tmp/test140-'));
  const file = path.join(dir, 'main.tex');
  await fs.writeFile(file, 'cat scatter cat\n<& cat\n');
  let result = await searchProject(dir, {query:'cat', wholeWord:true});
  assert.equal(result.matches.length, 3);
  result = await replaceProject(dir, {query:'cat', wholeWord:true, replacement:'$&'});
  assert.equal(result.replacements,3);
  assert.equal(await fs.readFile(file,'utf8'), '$& scatter $&\n<& $&\n');
  await fs.writeFile(file, 'abc');
  result = await searchProject(dir,{query:'(?=.)',regex:true});
  assert.deepEqual(result.matches.map(m=>m.col),[1,2,3]);
  await assert.rejects(searchProject(dir,{query:'[',regex:true}), /正则/);
  const project = new ProjectService({get:()=>true}, dir); project.root = dir;
  assert.equal(project.safePath('main.tex'),file);
  assert.equal(project.safePath('..notes.tex'),path.join(dir,'..notes.tex'));
  assert.throws(()=>project.safePath('../outside.tex'),/范围/);
  await assert.rejects(project.createFile(dir,'../outside.tex','oops'),/目录/);
  await assert.rejects(project.createDir(dir,'../outside'),/目录/);
  await assert.rejects(project.rename(file,'../outside.tex'),/目录/);
  await assert.rejects(project.saveImage(dir,'../outside.png','AA=='),/目录/);
  let changed=false;project.on('changed',()=>changed=true);
  project._pending=setTimeout(()=>project.emit('changed'),5);project.stopWatch();
  await new Promise(r=>setTimeout(r,15));assert.equal(changed,false);

  // Exercise actual application save functions with a delayed disk write.
  const source=await fs.readFile('src/main.js','utf8');
  const functions=source.slice(source.indexOf('function saveDocument('),source.indexOf('async function closeDocument('));
  const doc={model:{getValue:()=>value},dirty:true};let value='first',writeCount=0,release;
  const messages=[];const ctx={state:{docs:new Map([['main.tex',doc]]),settings:{files:{historyEnabled:false},build:{}},build:{}},cmd:()=>{}};
  const api={fs:{write:async(_p,text)=>{writeCount++;if(writeCount===1)await new Promise(r=>release=r);return {ok:true,mtime:1};}}};
  const sandbox={ctx,api,toast:m=>messages.push(m),renderTabs:()=>{},setBuildStatus:()=>{}};
  vm.createContext(sandbox);vm.runInContext(functions,sandbox);
  const first=sandbox.saveDocument('main.tex');
  await new Promise(r=>setImmediate(r));value='second';release();await first;
  assert.equal(doc.savedText,'first');assert.equal(doc.dirty,true);
  await sandbox.saveDocument('main.tex');assert.equal(doc.savedText,'second');assert.equal(doc.dirty,false);
  doc.dirty=true;api.fs.write=async()=>({ok:false,error:'disk full'});
  assert.equal(await sandbox.saveAll(),false);
  assert.equal(messages.some(m=>m.type==='success'),false);
  console.log('PASS 1.4.0: whole-word/literal replacement, zero-width search, path boundaries, watcher cleanup, edit-during-save and failed save-all.');
})().catch(error=>{console.error(error);process.exitCode=1;});
