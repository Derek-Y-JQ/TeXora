nodeFs.renameSync=(...args)=>{if(attempts++<1)throw Object.assign(Error('temporary lock'),{code:'EBUSY'});return renameSync(...args);};
try{replaceFileSync(from,to);}finally{nodeFs.renameSync=renameSync;}
